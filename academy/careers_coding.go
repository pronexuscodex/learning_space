package main

// Coding interview practice: the method, and the patterns that most
// interview problems are built from, each with practice problems written
// for the academy. In the think-first spirit there are no model answers:
// each problem has a ladder of hints, a question first, then a direction,
// then the key idea, and the complexity to aim for.

// Pattern is a family of problems that share one idea.
type Pattern struct {
	Name    string
	Signal  string   // what in a problem points to it
	Idea    string   // the core idea
	Steps   []string // how to apply it
	Pitfall string
	Cost    string // the usual time and space
	Drills  []Drill
}

// Drill is a practice problem.
type Drill struct {
	Title    string
	Task     string
	Examples string
	Hints    []string // a question, a direction, the key idea
	Target   string   // the complexity to aim for
}

// interviewMethod is how to work through any coding interview problem.
var interviewMethod = []struct{ Step, How string }{
	{"Understand", "Say the problem back in your own words. Ask about input size, value ranges, duplicates, negative numbers, empty input and what to return when there is no answer."},
	{"Examples", "Work one normal example and one edge case by hand, on paper, before any code."},
	{"Brute force", "Say the simplest correct approach and its cost first. It proves you understand the problem and gives you something to improve."},
	{"Optimise", "Ask: what work is repeated? Which pattern fits? Can sorting, a hash map or two pointers remove a loop?"},
	{"Plan", "Say the steps of your solution out loud before writing it, and get a nod from the interviewer."},
	{"Code", "Write clear code with good names and small helpers. Talk while you write, so the interviewer can follow and help."},
	{"Test", "Trace your example through the code line by line, then the edge cases. Find your own bugs before the interviewer does."},
	{"Analyse", "State the time and space complexity, and what you would improve with more time."},
}

